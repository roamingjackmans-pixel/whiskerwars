// Two fake clients: host creates room, guest joins, messages relay both ways.
import WebSocket from 'ws';
const url = process.argv[2] || 'ws://localhost:8080/ws';
const open = () => new Promise((res, rej) => { const w = new WebSocket(url); w.on('open', () => res(w)); w.on('error', rej); });
const next = (w, pred) => new Promise(res => { const h = raw => { const m = JSON.parse(raw); if (pred(m)) { w.off('message', h); res(m); } }; w.on('message', h); });
const host = await open(), guest = await open();
host.send(JSON.stringify({ t: 'host' }));
const { code } = await next(host, m => m.t === 'hosted');
console.log('room code', code);
guest.send(JSON.stringify({ t: 'join', code: 'ZZZZZ' }));
console.log('bad code ->', (await next(guest, m => m.t === 'error')).code);
const pj = next(host, m => m.t === 'peer-join');
guest.send(JSON.stringify({ t: 'join', code: code.toLowerCase() }));
console.log('guest ->', (await next(guest, m => m.t === 'joined')).t, '| host ->', (await pj).t);
const third = await open();
third.send(JSON.stringify({ t: 'join', code }));
console.log('third player ->', (await next(third, m => m.t === 'error')).code);
const g = next(guest, m => m.t === 'msg');
host.send(JSON.stringify({ t: 'msg', d: { type: 'snap', s: { t: 1.5 } } }));
console.log('guest got', JSON.stringify((await g).d));
const h = next(host, m => m.t === 'msg');
guest.send(JSON.stringify({ t: 'msg', d: { type: 'cmd', c: { k: 'send' } } }));
console.log('host got', JSON.stringify((await h).d));
const left = next(host, m => m.t === 'peer-leave');
guest.close();
console.log('host notified ->', (await left).t);
host.close(); third.close();
const t0 = Date.now(); let n = 0;
console.log('OK');
process.exit(0);
